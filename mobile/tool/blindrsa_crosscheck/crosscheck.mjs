// Cross-test helper for mobile/lib/crypto/rfc9474.dart.
// Uses @cloudflare/blindrsa-ts, the same library as the V18 server.
//
//   node crosscheck.mjs fixture <out.json>   -> make vectors with blindrsa-ts (test key only)
//   node crosscheck.mjs serve < request.json -> sign Dart's blinded messages and verify Dart's
//                                               final signatures, print JSON to stdout
import { RSABSSA } from '@cloudflare/blindrsa-ts';
import { readFileSync, writeFileSync } from 'node:fs';
import { webcrypto } from 'node:crypto';

const subtle = webcrypto.subtle;
const suite = RSABSSA.SHA384.PSS.Randomized();
const hex = (u8) => Buffer.from(u8).toString('hex');
const unhex = (s) => new Uint8Array(Buffer.from(s, 'hex'));
const IMPORT = { name: 'RSA-PSS', hash: 'SHA-384' };

async function fixture(outPath) {
  const { publicKey, privateKey } = await suite.generateKey({
    modulusLength: 2048,
    publicExponent: new Uint8Array([1, 0, 1]),
  });
  const jwk = await subtle.exportKey('jwk', privateKey);
  const cases = [];
  for (let i = 0; i < 5; i++) {
    const msg = new TextEncoder().encode(
      JSON.stringify({ v: 1, ticketId: `crosscheck-${i}`, origin: 'https://example-site.test', minAge: 18 }));
    const prepared = suite.prepare(msg);
    const { blindedMsg, inv } = await suite.blind(publicKey, prepared);
    const blindSig = await suite.blindSign(privateKey, blindedMsg);
    const sig = await suite.finalize(publicKey, prepared, blindSig, inv);
    if (!(await suite.verify(publicKey, sig, prepared))) throw new Error('self check failed');
    cases.push({ msg: hex(msg), prepared: hex(prepared), blindedMsg: hex(blindedMsg), inv: hex(inv), blindSig: hex(blindSig), sig: hex(sig) });
  }
  const out = {
    source: '@cloudflare/blindrsa-ts 0.4.6, RSABSSA-SHA384-PSS-Randomized. TEST KEY ONLY, generated by mobile/tool/blindrsa_crosscheck.',
    jwk, cases,
  };
  writeFileSync(outPath, JSON.stringify(out, null, 1));
  console.log(`wrote ${cases.length} cases to ${outPath}`);
}

async function serve() {
  const req = JSON.parse(readFileSync(0, 'utf8'));
  const privateKey = await subtle.importKey('jwk', req.jwk, IMPORT, true, ['sign']);
  const { d, p, q, dp, dq, qi, ...pub } = req.jwk;
  const publicKey = await subtle.importKey('jwk', { ...pub, key_ops: ['verify'] }, IMPORT, true, ['verify']);
  const blindSigs = [];
  for (const b of req.blindedMsgs ?? []) blindSigs.push(hex(await suite.blindSign(privateKey, unhex(b))));
  const verified = [];
  for (const c of req.verify ?? []) verified.push(await suite.verify(publicKey, unhex(c.sig), unhex(c.prepared)));
  process.stdout.write(JSON.stringify({ blindSigs, verified }));
}

const [mode, arg] = process.argv.slice(2);
if (mode === 'fixture') await fixture(arg);
else if (mode === 'serve') await serve();
else { console.error('usage: crosscheck.mjs fixture <out.json> | serve'); process.exit(2); }
